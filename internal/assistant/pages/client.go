// Package pages is a client for Grafana Assistant Pages: published pages in the
// page catalog and the source projects behind them.
package pages

import (
	"context"
	"errors"
	"fmt"
	"net/http"
	"net/url"
	"strconv"
	"strings"
	"time"

	"github.com/grafana/gcx/internal/assistant/assistanthttp"
	"github.com/grafana/gcx/internal/gcxerrors"
)

const (
	catalogPath = "/api/v1/page-catalog"
	chatsPath   = "/api/v1/chats"

	// chatOrigin marks conversations gcx opens to edit a page.
	chatOrigin = "grafana-assistant-app/pages"
)

// ErrSourceUnsupported reports an Assistant that does not take a pushed
// source for a page edit yet.
var ErrSourceUnsupported = errors.New("this Grafana Assistant does not accept pushed page source yet")

// Entry is a published page as the catalog lists it.
type Entry struct {
	ID          string    `json:"id"`
	Title       string    `json:"title"`
	Description string    `json:"description"`
	Category    string    `json:"category"`
	Tags        []string  `json:"tags"`
	FolderUID   string    `json:"folderUid"`
	Unlisted    bool      `json:"unlisted,omitempty"`
	LinkSharing bool      `json:"linkSharing,omitempty"`
	SharedWith  []Share   `json:"sharedWith,omitempty"`
	OwnerUserID string    `json:"ownerUserId"`
	RevisionID  string    `json:"revisionId"`
	Version     int       `json:"version"`
	Published   bool      `json:"published"`
	Views       int       `json:"views"`
	UpdatedAt   time.Time `json:"updatedAt"`
	UpdatedBy   string    `json:"updatedBy,omitempty"`
}

// Share is a person a page is shared with.
type Share struct {
	UserID int64  `json:"userId"`
	Login  string `json:"login"`
}

// Source is a page's source project: paths relative to the project root and
// their bytes, which travel base64-encoded.
type Source struct {
	Version int               `json:"version"`
	Files   map[string][]byte `json:"files"`
}

// Export is a published page's source and speaker notes.
type Export struct {
	Source       Source            `json:"source"`
	SpeakerNotes map[string]string `json:"speakerNotes,omitempty"`
}

// Page is a page in a conversation's workspace.
type Page struct {
	ID             string `json:"id"`
	ChatID         string `json:"chatId"`
	Title          string `json:"title"`
	ReleaseID      string `json:"releaseId,omitempty"`
	CandidateID    string `json:"candidateId,omitempty"`
	Error          string `json:"error,omitempty"`
	RebuildPending bool   `json:"rebuildPending,omitempty"`
	EditOfID       string `json:"editOfId,omitempty"`
}

// ListOptions narrows a catalog listing.
type ListOptions struct {
	// Section is discover, mine, starred or unlisted.
	Section string
	Search  string
	Limit   int
	Cursor  string
}

// Client calls the Assistant Pages API.
type Client struct {
	base *assistanthttp.Client
}

// NewClient wraps an Assistant HTTP client.
func NewClient(base *assistanthttp.Client) *Client { return &Client{base: base} }

// List returns one batch of catalog pages and the cursor of the next, empty
// when the listing is complete.
func (c *Client) List(ctx context.Context, opts ListOptions) ([]Entry, string, error) {
	q := url.Values{}
	if opts.Section != "" {
		q.Set("section", opts.Section)
	}
	if opts.Search != "" {
		q.Set("search", opts.Search)
	}
	if opts.Limit > 0 {
		q.Set("limit", strconv.Itoa(opts.Limit))
	}
	if opts.Cursor != "" {
		q.Set("cursor", opts.Cursor)
	}
	path := catalogPath
	if len(q) > 0 {
		path += "?" + q.Encode()
	}
	out, err := assistanthttp.DoEnvelopeRequest[struct {
		Pages      []Entry `json:"pages"`
		NextCursor string  `json:"nextCursor"`
	}](c.base, ctx, http.MethodGet, path, nil, "list pages")
	if err != nil {
		return nil, "", classify(err)
	}
	if out.Pages == nil {
		out.Pages = []Entry{}
	}
	return out.Pages, out.NextCursor, nil
}

// Get returns one published page.
func (c *Client) Get(ctx context.Context, id string) (*Entry, error) {
	out, err := assistanthttp.DoEnvelopeRequest[struct {
		Page Entry `json:"page"`
	}](c.base, ctx, http.MethodGet, catalogPath+"/"+url.PathEscape(id), nil, "get page")
	if err != nil {
		return nil, classify(err)
	}
	return &out.Page, nil
}

// Export returns the source of a published page's revision.
func (c *Client) Export(ctx context.Context, id, revision string) (*Export, error) {
	path := catalogPath + "/" + url.PathEscape(id) + "/export?revision=" + url.QueryEscape(revision)
	out, err := assistanthttp.DoEnvelopeRequest[Export](c.base, ctx, http.MethodGet, path, nil, "export page")
	if err != nil {
		return nil, classify(err)
	}
	return out, nil
}

// CreateChat opens a new conversation for editing a page.
func (c *Client) CreateChat(ctx context.Context, name string) (string, error) {
	req := map[string]any{"name": name, "nameAutogenerated": false, "origin": chatOrigin, "engine": "aisdk"}
	out, err := assistanthttp.DoEnvelopeRequest[struct {
		ID string `json:"id"`
	}](c.base, ctx, http.MethodPost, chatsPath, req, "create conversation")
	if err != nil {
		return "", classify(err)
	}
	if out.ID == "" {
		return "", errors.New("create conversation: the response has no conversation id")
	}
	return out.ID, nil
}

// EditFromSource copies a published page into a new conversation with the
// caller's source in place of the published revision. The copy is built by
// Rebuild and becomes the publication's next version with Accept and
// Publish.
func (c *Client) EditFromSource(ctx context.Context, id, chatID string, export Export) (*Page, error) {
	req := map[string]any{"chatId": chatID, "source": export.Source}
	if len(export.SpeakerNotes) > 0 {
		req["speakerNotes"] = export.SpeakerNotes
	}
	page, err := c.pageRequest(ctx, http.MethodPost, catalogPath+"/"+url.PathEscape(id)+"/edit", req, "edit page")
	if err != nil {
		var status *gcxerrors.HTTPStatusError
		// An Assistant without source edits rejects the unknown field.
		if errors.As(err, &status) && status.Status == http.StatusUnprocessableEntity && strings.Contains(status.ServerMessage, "source") {
			return nil, fmt.Errorf("%w: %w", ErrSourceUnsupported, err)
		}
		return nil, err
	}
	// An Assistant that ignored the source copied the published revision;
	// publishing that copy would silently drop the pushed changes.
	if !page.RebuildPending {
		return nil, fmt.Errorf("%w: the edit copied the published revision instead of the pushed source", ErrSourceUnsupported)
	}
	return page, nil
}

// Rebuild builds a conversation's page from its saved source. The result
// carries the build's candidate or its compile error.
func (c *Client) Rebuild(ctx context.Context, chatID, pageID string) (*Page, error) {
	return c.pageRequest(ctx, http.MethodPost, chatsPath+"/"+url.PathEscape(chatID)+"/pages/"+url.PathEscape(pageID)+"/rebuild", map[string]any{}, "build page")
}

// Accept makes a built candidate the page's release.
func (c *Client) Accept(ctx context.Context, chatID, pageID, candidate string) (*Page, error) {
	return c.pageRequest(ctx, http.MethodPost, chatsPath+"/"+url.PathEscape(chatID)+"/pages/"+url.PathEscape(pageID)+"/accept", map[string]any{"candidate": candidate}, "accept build")
}

// Publish publishes a release as the next version of an existing
// publication, keeping its details and sharing.
func (c *Client) Publish(ctx context.Context, entry *Entry, pageID, releaseID string) (*Entry, error) {
	tags := entry.Tags
	if tags == nil {
		tags = []string{}
	}
	users := entry.SharedWith
	if users == nil {
		users = []Share{}
	}
	req := map[string]any{
		"id": entry.ID, "version": entry.Version, "pageId": pageID, "releaseId": releaseID,
		"metadata": map[string]any{
			"title": entry.Title, "description": entry.Description, "category": entry.Category,
			"tags": tags, "folderUid": entry.FolderUID, "unlisted": entry.Unlisted,
		},
		"sharing": map[string]any{"users": users, "linkSharing": entry.LinkSharing},
	}
	out, err := assistanthttp.DoEnvelopeRequest[struct {
		Page Entry `json:"page"`
	}](c.base, ctx, http.MethodPost, catalogPath, req, "publish page")
	if err != nil {
		return nil, classify(err)
	}
	return &out.Page, nil
}

func (c *Client) pageRequest(ctx context.Context, method, path string, req any, op string) (*Page, error) {
	out, err := assistanthttp.DoEnvelopeRequest[struct {
		Page Page `json:"page"`
	}](c.base, ctx, method, path, req, op)
	if err != nil {
		return nil, classify(err)
	}
	return &out.Page, nil
}

// classify adds recovery advice to the API errors a caller can act on.
func classify(err error) error {
	var status *gcxerrors.HTTPStatusError
	if !errors.As(err, &status) {
		return err
	}
	switch {
	case status.Status == http.StatusConflict && strings.Contains(status.ServerMessage, "page-changed"):
		return fmt.Errorf("%w (someone published a newer version since you pulled; pull it again, reapply your changes and push)", err)
	case status.Status == http.StatusNotFound:
		return fmt.Errorf("%w (check the page id with gcx assistant pages list, and that Pages is enabled on this stack)", err)
	case status.Status == http.StatusForbidden:
		return fmt.Errorf("%w (your identity cannot open or edit this page, or Pages import and export is off on this stack)", err)
	}
	return err
}
